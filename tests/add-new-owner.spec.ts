import { test, expect } from "@playwright/test";
import { faker, fakerEN_GB } from "@faker-js/faker";

test.beforeEach(async ({ page }) => {
  await page.goto("/");
});

test("Add new Owner", async ({ page }) => {
  // Will use the FAKER library to generate random data for the new owner

  const randomName = faker.person.firstName();
  const randomLastName = faker.person.lastName();
  const randomAddress = fakerEN_GB.location.postalAddress();
  const randomCity = fakerEN_GB.location.city();
  const randomPhoneNumber = faker.string.numeric(10);

  await expect(page.locator(".title")).toHaveText("Welcome to Petclinic");
  // select pet types menu item
  await page.getByRole("button", { name: "Owners" }).click();
  await page.getByRole("link", { name: "Add New" }).click();
  // add assertion of 'New Owner' text displaying
  await expect(page.getByRole("heading", { name: "New Owner" })).toBeVisible();

  // click on the first name and last name text boxes and fill in with random names generated by FAKER
  await page.getByRole("textbox", { name: "First Name" }).fill(randomName);
  await page.getByRole("textbox", { name: "Last Name" }).fill(randomLastName);
  // click on the address text box and fill in with random address generated by FAKER
  await page.getByRole("textbox", { name: "Address" }).fill(randomAddress);
  // click on the city text box and fill in with random city generated by FAKER
  await page.getByRole("textbox", { name: "City" }).fill(randomCity);
  // click on the mobile number text box and fill in with random phone number generated by FAKER
  await page
    .getByRole("textbox", { name: "Telephone" })
    .fill(randomPhoneNumber);

  // click on the 'Add Owner' button
  await page.getByRole("button", { name: "Add Owner" }).click();

  // add assertion of 'Owners' page text displaying
  await expect(page.getByRole("heading", { name: "Owners" })).toBeVisible();
});

test("Click Back button on New Owner page", async ({ page }) => {
  await expect(page.locator(".title")).toHaveText("Welcome to Petclinic");
  // select pet types menu item
  await page.getByRole("button", { name: "Owners" }).click();
  await page.getByRole("link", { name: "Add New" }).click();
  // add assertion of 'New Owner' text displaying
  await expect(page.getByRole("heading", { name: "New Owner" })).toBeVisible();
  // click on the 'Back' button
  await page.getByRole("button", { name: "Back" }).click();
  // add assertion of 'Owners' page text displaying
  await expect(page.getByRole("heading", { name: "Owners" })).toBeVisible();
});
